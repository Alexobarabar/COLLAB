import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { generateDigitalSignature, getCurrentUserForSignature } from './signature';

const DEFAULT_TAGLINE = 'Generated by the Dean Dashboard System';
const FALLBACK_TEXT = 'Not specified';
const DEFAULT_LOGO_PATHS = {
  left: '/buksu-logo.png',
  right: '/cot-logo.jpg',
};

const resolveAssetPath = (src) => {
  if (!src) return null;
  if (src.startsWith('data:') || /^https?:\/\//i.test(src)) {
    return src;
  }
  const baseUrl = typeof window !== 'undefined' ? window.location.origin : '';
  if (!baseUrl) {
    return src.startsWith('/') ? src : `/${src}`;
  }
  return src.startsWith('/') ? `${baseUrl}${src}` : `${baseUrl}/${src}`;
};

const fetchImageAsDataUrl = async (src) => {
  if (!src) return null;
  const resolved = resolveAssetPath(src);
  try {
    const response = await fetch(resolved, { cache: 'force-cache' });
    if (!response.ok) {
      throw new Error(`Unable to load logo: ${response.statusText}`);
    }
    const blob = await response.blob();
    return await new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onloadend = () => resolve(reader.result);
      reader.onerror = reject;
      reader.readAsDataURL(blob);
    });
  } catch (error) {
    console.warn('[PDF] Failed to load image for header', src, error);
    return null;
  }
};

const getImageFormat = (dataUrl) => {
  if (!dataUrl || typeof dataUrl !== 'string') return 'PNG';
  if (dataUrl.startsWith('data:image/jpeg') || dataUrl.startsWith('data:image/jpg')) return 'JPEG';
  if (dataUrl.startsWith('data:image/webp')) return 'WEBP';
  return 'PNG';
};

const formatScore = (value) => {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return Number(value).toFixed(2);
  }
  return '—';
};

const asText = (value, fallback = FALLBACK_TEXT) => {
  if (value === 0) {
    return '0';
  }
  return value ? String(value) : fallback;
};

const gatherQuestionList = (payload = {}) => {
  if (Array.isArray(payload.allQuestions) && payload.allQuestions.length) {
    return payload.allQuestions;
  }

  const merged = [
    ...(Array.isArray(payload.generalIndicators) ? payload.generalIndicators : []),
    ...(Array.isArray(payload.masteryIndicators) ? payload.masteryIndicators : []),
  ];

  return merged;
};

// Metadata fields to exclude from question tables
const METADATA_KEYWORDS = [
  'student name', 'name', 'first name', 'last name', 'student first name', 'student last name',
  'full name', 'fullname', 'studentname', 'student_name',
  'year level', 'yearlevel', 'year_level', 'yr level', 'year',
  'section code', 'subject code', 'select instructor', 'course',
  'student id', 'student email', 'student email address',
  'timestamp', 'instructor name', 'instructor email', 'instructor email address'
];

const shouldExcludeQuestion = (questionText) => {
  if (!questionText) return true;
  const normalized = String(questionText).toLowerCase().trim();
  return METADATA_KEYWORDS.some(keyword => normalized === keyword || normalized.includes(keyword));
};

const buildQuestionRows = (payload) => {
  const questions = gatherQuestionList(payload)
    .filter((question) => {
      const questionText = question?.question || question?.questionText || '';
      return !shouldExcludeQuestion(questionText);
    });

  if (!questions.length) {
    return [['No evaluation questions available', '—']];
  }

  return questions.map((question, index) => {
    const label = question?.question || question?.questionText || `Untitled Question ${index + 1}`;
    return [`${index + 1}. ${label}`, formatScore(question?.average)];
  });
};

