const addCommentsSection = (doc, payload, startY) => {
  const comments = Array.isArray(payload.textResponses) ? payload.textResponses : [];
  if (!comments.length) {
    return startY;
  }

  const rows = comments.map((response, index) => [
    `${index + 1}. ${response.question || 'Question'}`,
    response.response || '—',
  ]);

  autoTable(doc, {
    head: [['Question', 'Comment']],
    body: rows,
    startY,
    theme: 'grid',
    styles: { fontSize: 9, cellPadding: 3, valign: 'top' },
    headStyles: { fillColor: [24, 58, 94], textColor: 255 },
    columnStyles: {
      0: { cellWidth: 70 },
      1: { cellWidth: 100 },
    },
    margin: { left: 14, right: 14 },
  });

  return doc.lastAutoTable?.finalY || startY;
};

const addIndividualResponsesSection = (doc, payload, startY) => {
  const individualResponses = Array.isArray(payload.individualResponses) ? payload.individualResponses : [];
  if (!individualResponses.length) {
    return startY;
  }

  const marginX = 14;
  let currentY = startY;

  // Metadata columns to exclude from display - includes all variations of student name and year level
  const metadataColumns = new Set([
    'timestamp', 'instructor name', 'instructor email', 'instructor email address',
    'student id', 'student email', 'student email address', 'section code',
    'subject code', 'course', 'semester', 'academic year', 'year level', 'year',
    'select instructor', 'student name', 'name', 'first name', 'last name',
    'student first name', 'student last name', 'yearlevel', 'year_level', 'yr level',
    'studentname', 'student_name', 'studentname', 'full name', 'fullname'
  ]);

  const isNumericQuestion = (questionText, allAnswers) => {
    const lowerText = questionText.toLowerCase();
    if (lowerText.includes('(1-5)') || lowerText.includes('rating') || lowerText.includes('rate')) {
      return true;
    }
    if (lowerText.includes('comment') || lowerText.includes('feedback') || lowerText.includes('suggestion')) {
      return false;
    }
    if (allAnswers && allAnswers.length > 0) {
      const numericCount = allAnswers.filter(answer => {
        const num = parseFloat(answer);
        return !isNaN(num) && isFinite(num) && num > 0;
      }).length;
      return numericCount > allAnswers.length / 2;
    }
    return true;
  };

  const questionList = [];
  const questionMap = new Map();

  if (payload.allQuestions && Array.isArray(payload.allQuestions) && payload.allQuestions.length > 0) {
    payload.allQuestions.forEach((q) => {
      const questionText = q.question || q.questionText || '';
      if (questionText && questionText.trim()) {
        const normalized = questionText.trim();
        const lowerHeader = normalized.toLowerCase();
        if (!metadataColumns.has(lowerHeader)) {
          questionList.push({
            text: normalized,
            isNumeric: q.isNumeric !== undefined ? q.isNumeric : (q.questionType === 'rating' || q.questionType === 'multiple_choice')
          });
          questionMap.set(normalized.toLowerCase(), normalized);
        }
      }
    });
  }

  if (individualResponses.length > 0 && individualResponses[0].answers) {
    Object.keys(individualResponses[0].answers).forEach((header) => {
      if (header && header.trim()) {
        const normalized = header.trim();
        const lowerHeader = normalized.toLowerCase();
        if (!metadataColumns.has(lowerHeader) && !questionMap.has(lowerHeader)) {
          const allAnswersForQuestion = individualResponses
            .map(r => {
              const answer = r.answers?.[normalized];
              return answer !== undefined && answer !== null && String(answer).trim() !== '' ? String(answer).trim() : null;
            })
            .filter(a => a !== null);
          
          questionList.push({
            text: normalized,
            isNumeric: isNumericQuestion(normalized, allAnswersForQuestion)
          });
          questionMap.set(lowerHeader, normalized);
        }
      }
    });
  }

  if (questionList.length === 0) {
    return startY;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  currentY += 10;
  doc.text('Student Responses Summary', marginX, currentY);
  currentY += 4;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Total Respondents: ${individualResponses.length}`, marginX, currentY);
  currentY += 10;

  const tableBody = questionList.map((questionItem, questionIndex) => {
    const questionText = questionItem.text;
    const isNumeric = questionItem.isNumeric;

    if (isNumeric) {
      const answers = [];
      individualResponses.forEach((response) => {
        let answer = response.answers?.[questionText];
        if (answer === undefined || answer === null || answer === '') {
          const matchingKey = Object.keys(response.answers || {}).find(
            (key) => key.toLowerCase().trim() === questionText.toLowerCase().trim()
          );
          if (matchingKey) {
            answer = response.answers[matchingKey];
          }
        }
        if (answer !== undefined && answer !== null && String(answer).trim() !== '') {
          const num = parseFloat(String(answer).trim());
          if (!isNaN(num) && isFinite(num)) {
            answers.push(num);
          }
        }
      });

      let averageText = '—';
      if (answers.length > 0) {
        const average = answers.reduce((sum, val) => sum + val, 0) / answers.length;
        const roundedAverage = Math.round(average * 100) / 100;
        averageText = formatScore(roundedAverage);
      }

      return [`${questionIndex + 1}. ${questionText}`, averageText];
    } else {
      const comments = [];
      individualResponses.forEach((response) => {
        let answer = response.answers?.[questionText];
        if (answer === undefined || answer === null || answer === '') {
          const matchingKey = Object.keys(response.answers || {}).find(
            (key) => key.toLowerCase().trim() === questionText.toLowerCase().trim()
          );
          if (matchingKey) {
            answer = response.answers[matchingKey];
          }
        }
        if (answer !== undefined && answer !== null && String(answer).trim() !== '') {
          comments.push(String(answer).trim());
        }
      });

      let commentsText = '—';
      if (comments.length > 0) {
        commentsText = comments.map((comment, idx) => `${idx + 1}. ${comment}`).join('\n');
      }

      return [`${questionIndex + 1}. ${questionText}`, commentsText];
    }
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const availableWidth = pageWidth - (marginX * 2);
  const questionColumnWidth = availableWidth * 0.4;
  const answerColumnWidth = availableWidth * 0.6;

  autoTable(doc, {
    head: [['Question', 'Average']],
    body: tableBody,
    startY: currentY,
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 3, valign: 'top' },
    headStyles: { fillColor: [70, 130, 180], textColor: 255, fontSize: 9 },
    columnStyles: {
      0: { cellWidth: questionColumnWidth, fontStyle: 'bold' },
      1: { cellWidth: answerColumnWidth, cellMinHeight: 6 },
    },
    margin: { left: marginX, right: marginX },
    didParseCell: (data) => {
      if (data.column.index === 1 && data.cell.text && String(data.cell.text).includes('\n')) {
        data.cell.text = String(data.cell.text).split('\n');
      } else if (data.column.index === 1 && data.cell.text) {
        const text = String(data.cell.text);
        if (text.length > 80) {
          const words = text.split(' ');
          const lines = [];
          let currentLine = '';
          words.forEach((word) => {
            if ((currentLine + word).length > 80) {
              if (currentLine) lines.push(currentLine.trim());
              currentLine = word + ' ';
            } else {
              currentLine += word + ' ';
            }
          });
          if (currentLine) lines.push(currentLine.trim());
          data.cell.text = lines;
        }
      }
    },
  });

  currentY = doc.lastAutoTable?.finalY || currentY;
  currentY += 10;

  return currentY;
};

const addFooter = (doc, tagline = DEFAULT_TAGLINE, footerText = '') => {
  const pageCount = doc.internal.getNumberOfPages();

  for (let pageNumber = 1; pageNumber <= pageCount; pageNumber += 1) {
    doc.setPage(pageNumber);
    const pageHeight = doc.internal.pageSize.getHeight();
    const pageWidth = doc.internal.pageSize.getWidth();

    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    if (footerText) {
      doc.text(footerText, 14, pageHeight - 13, { maxWidth: pageWidth - 28 });
    }
    doc.text(tagline, 14, pageHeight - 7);
    doc.text(`Page ${pageNumber} of ${pageCount}`, pageWidth - 14, pageHeight - 7, {
      align: 'right',
    });
  }
};

const openPdf = (doc, fileName) => {
  try {
    const blob = doc.output('blob');
    const blobUrl = URL.createObjectURL(blob);
    const popup = window.open(blobUrl);

    if (!popup) {
      doc.save(fileName);
      URL.revokeObjectURL(blobUrl);
      return;
    }

    popup.onload = () => {
      setTimeout(() => URL.revokeObjectURL(blobUrl), 60_000);
    };
  } catch (error) {
    console.error('Unable to open PDF in new tab, falling back to download.', error);
    doc.save(fileName);
  }
};

const generateInstructorReportPdf = async (payload) => {
  if (!payload) {
    throw new Error('Cannot generate PDF without payload data.');
  }

  const leftLogoPath = payload?.headerLogos?.left || DEFAULT_LOGO_PATHS.left;
  const rightLogoPath = payload?.headerLogos?.right || DEFAULT_LOGO_PATHS.right;

  const [leftLogoDataUrl, rightLogoDataUrl] = await Promise.all([
    fetchImageAsDataUrl(leftLogoPath),
    fetchImageAsDataUrl(rightLogoPath),
  ]);

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const headerBottom = addHeader(
    doc,
    payload,
    {
      left: leftLogoDataUrl ? { dataUrl: leftLogoDataUrl, format: getImageFormat(leftLogoDataUrl) } : null,
      right: rightLogoDataUrl ? { dataUrl: rightLogoDataUrl, format: getImageFormat(rightLogoDataUrl) } : null,
    }
  );
  // Instructor dashboard print report: only show the section summary table
  const sectionTableBottom = addSectionSummaryTable(doc, payload, headerBottom + 6);
  // First footer pass
  addFooter(doc, DEFAULT_TAGLINE, '');

  const pdfArrayBuffer = doc.output('arraybuffer');
  const user = getCurrentUserForSignature();
  const { footerText, signatureHash, signatureId } = generateDigitalSignature(user, pdfArrayBuffer);

  doc.setProperties({
    title: `Instructor Performance - ${asText(payload.instructorName, 'Instructor')}`,
    subject: 'Digitally signed instructor performance report',
    author: user.email,
    keywords: `digital-signature,sha256,SignatureID=${signatureId},SignatureHash=${signatureHash}`,
    creator: 'Buksu IT Instructor Evaluation System',
  });

  // Final footer with signature text
  addFooter(doc, DEFAULT_TAGLINE, footerText);

  const normalizedName = asText(payload.instructorName, 'instructor')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    || 'instructor';
  const fileName = `instructor-performance-${normalizedName}.pdf`;
  openPdf(doc, fileName);

  return sectionTableBottom;
};

export default generateInstructorReportPdf;

