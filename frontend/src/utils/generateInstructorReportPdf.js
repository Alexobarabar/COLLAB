const addSummaryTable = (doc, payload, startY) => {
  const summaryRows = [
    ['Total Average', formatScore(payload.totalAverage)],
    ['Rating Equivalent', asText(payload.totalDescriptor, '—')],
  ];

  if (typeof payload.conversionScore === 'number') {
    summaryRows.push(['Faculty Reclassification Score', `${payload.conversionScore}`]);
  }

  autoTable(doc, {
    head: [['Summary', 'Value']],
    body: summaryRows,
    startY,
    theme: 'grid',
    styles: { fontSize: 10, cellPadding: 3 },
    headStyles: { fillColor: [102, 126, 234], textColor: 255 },
    columnStyles: {
      0: { cellWidth: 90 },
      1: { cellWidth: 80 },
    },
    margin: { left: 14, right: 14 },
  });

  return doc.lastAutoTable?.finalY || startY;
};

const addSectionSummaryTable = (doc, payload, startY) => {
  const sections = Array.isArray(payload.sectionSummary) ? payload.sectionSummary : [];
  // Only extract the three fields we need: sectionCode, respondents/totalStudents, and average
  // Explicitly exclude any student names, year levels, or other personal information
  const rows = sections.length
    ? sections.map((row, idx) => {
        // Only extract the specific fields we want to display
        const sectionCode = row.sectionCode || `Section ${idx + 1}`;
        const respondents = row.respondents || 0;
        const totalStudents = row.totalStudents || 0;
        const average = formatScore(row.average);
        
        // Return only the three columns: Section Code, Respondents, Average
        // No student names, year levels, or other personal data
        return [
          sectionCode,
          `${respondents} / ${totalStudents}`,
          average,
        ];
      })
    : [['No section data available', '—', '—']];

  autoTable(doc, {
    head: [['Section Code', 'Respondents', 'Average']],
    body: rows,
    startY,
    theme: 'grid',
    styles: { fontSize: 10, cellPadding: 3, valign: 'middle' },
    headStyles: { fillColor: [46, 125, 50], textColor: 255 },
    columnStyles: {
      0: { cellWidth: 80 },
      1: { cellWidth: 50, halign: 'center' },
      2: { cellWidth: 40, halign: 'center' },
    },
    margin: { left: 14, right: 14 },
  });

  return doc.lastAutoTable?.finalY || startY;
};

